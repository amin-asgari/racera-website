import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repository = process.argv[2]?.trim();
const repositoryPattern = /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/;

if (!repository || !repositoryPattern.test(repository)) {
  console.error("Usage: pnpm downloads:configure GITHUB_OWNER/GITHUB_REPOSITORY");
  process.exit(1);
}

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const redirectsPath = path.join(projectRoot, "public", "_redirects");
const releaseBase = `https://github.com/${repository}/releases/latest/download`;
const redirects = [
  "# Generated by scripts/configure-downloads.mjs.",
  "# Keep these asset names unchanged in every published GitHub Release.",
  `/download/android ${releaseBase}/Racera-Android.apk 302`,
  `/download/ios ${releaseBase}/Racera-iOS.ipa 302`,
  "",
].join("\n");

await writeFile(redirectsPath, redirects, "utf8");

console.log(`Download redirects now use the latest release from ${repository}.`);
console.log("Android asset: Racera-Android.apk");
console.log("iOS asset: Racera-iOS.ipa");
